#!/usr/bin/env bash
# generate-tfvars.sh — reads environments.properties and exports pipeline variables
# Also writes a sandbox.tfvars file with values from environments.properties
# Usage: source env_config/generate-tfvars.sh [sandbox]
set -euo pipefail

ENVIRONMENT="${1:-${ENVIRONMENT:-sandbox}}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROPS_FILE="${SCRIPT_DIR}/environments.properties"
TFVARS_FILE="${SCRIPT_DIR}/${ENVIRONMENT}.tfvars"

parse_section() {
  local section="$1"
  local in_section=false
  while IFS='=' read -r key value; do
    [[ "$key" =~ ^#.*$ || -z "$key" ]] && continue
    key="${key// /}"
    if [[ "$key" == "[$section]" ]]; then
      in_section=true
      continue
    fi
    if [[ "$key" =~ ^\[.*\]$ ]]; then
      in_section=false
      continue
    fi
    if $in_section; then
      value="${value//\"/}"
      export "$key"="$value"
    fi
  done < "$PROPS_FILE"
}

# Load COMMON first, then environment-specific (overrides COMMON)
parse_section "COMMON"
parse_section "$ENVIRONMENT"

# Write tfvars file from parsed values
cat > "${TFVARS_FILE}" <<EOF
# Auto-generated by generate-tfvars.sh — do not edit manually
environment       = "${ENVIRONMENT}"
aws_region        = "${DEPLOY_REGION}"
target_account_id = "${SBX_ACCOUNT_ID}"
mgmt_account_id   = "${SBX_MGMT_ACCOUNT_ID}"
map_migrated      = "${MAP_MIGRATED}"

tags = {
  cost-center = "${ENVIRONMENT}"
}
EOF

echo "Loaded config for environment: $ENVIRONMENT"
echo "  SBX_ACCOUNT_ID     = ${SBX_ACCOUNT_ID:-}"
echo "  SBX_MGMT_ACCOUNT_ID= ${SBX_MGMT_ACCOUNT_ID:-}"
echo "  DEPLOY_REGION      = ${DEPLOY_REGION:-}"
echo "  BACKEND_REGION     = ${BACKEND_REGION:-}"
echo "  DYNAMODB_TABLE     = ${DYNAMODB_TABLE:-}"
echo "  STATE_BUCKET       = ${STATE_BUCKET:-}"
echo "  MAP_MIGRATED       = ${MAP_MIGRATED:-}"
echo "  Generated tfvars   = ${TFVARS_FILE}"
